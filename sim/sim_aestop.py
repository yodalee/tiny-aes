"""End-to-end AES tests for the byte-streaming AesTop interface.

Each transaction sends the 16-byte input block first, followed by its key.
Encryption tests exercise both encryption encodings of the byte-streaming
path.  Decryption tests remain skipped until ControlFsm implements separate
last-round-key and first-round-key schedules.
"""

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import ReadWrite, RisingEdge


DATA = bytes.fromhex("00112233445566778899aabbccddeeff")
KEY_LEVEL = {16: 0b00, 24: 0b01, 32: 0b10}
INPUT_STROBE_CYCLES = 5
OUTPUT_STROBE_CYCLES = 4

# AES ECB results for DATA=00112233445566778899aabbccddeeff and the
# incrementing key of the corresponding length.  These are the three FIPS-197
# encryption known-answer values.  A decrypt transaction consumes the matching
# ciphertext below and must recover DATA.
EXPECTED = {
    16: bytes.fromhex("69c4e0d86a7b0430d8cdb78070b4c55a"),
    24: bytes.fromhex("dda97ca4864cdfe06eaf70a0ec0d7191"),
    32: bytes.fromhex("8ea2b7ca516745bfeafc49904b496089"),
}

# Decryption starts from the end of the key schedule.  AesTop's key register
# is key-width wide, therefore AES-192/AES-256 need the final 24/32-byte key
# schedule state (not merely the final 16-byte AddRoundKey value).  These
# values are generated by model.aes.decryption_key_state(bytes(range(n))).
DECRYPTION_KEY_STATE = {
    16: bytes.fromhex("13111d7fe3944a17f307a78b4d2b30c5"),
    24: bytes.fromhex("a223800fd8aeda32a4970a331a78dc09c418c271e3a41d5d"),
    32: bytes.fromhex("4e5a6699a9f24fe07e572baacdf8cdea24fc79ccbf0979e9371ac23c6d68de36"),
}


def as_int(value):
    return int(value)


async def reset(dut):
    dut.rst_n.value = 0
    dut.i_valid.value = 0
    dut.i_data.value = 0
    dut.o_ready.value = 1
    await RisingEdge(dut.clk)
    await RisingEdge(dut.clk)
    dut.rst_n.value = 1
    await RisingEdge(dut.clk)


async def run_aes(dut, r_dec, input_bytes, key_bytes):
    """Run one transaction with periodic valid/ready software strobes.

    After every rising edge, this coroutine waits for the writable simulation
    phase and selects signals for the *next* rising edge.  Thus it uses no
    falling-edge trigger.  The output byte is saved before its accepting edge,
    because that edge can advance the AES state before the next writable
    phase.
    """
    dut.r_dec.value = r_dec
    dut.r_level.value = KEY_LEVEL[len(key_bytes)]
    await reset(dut)

    input_stream = input_bytes + key_bytes
    input_index = 0
    input_valid = False
    actual = bytearray()
    pending_input_taken = False
    pending_output_data = None

    # Software issues exactly one input request every five cycles.  The output
    # consumer accepts exactly one byte every four cycles.
    for cycle in range(10_000):
        # RisingEdge itself can resume before all clocked and combinational
        # RTL processes have run.  ReadWrite makes the current-cycle signals
        # stable, while still allowing us to drive the next-cycle handshake.
        await ReadWrite()

        if pending_input_taken:
            input_index += 1
            input_valid = False
        if pending_output_data is not None:
            actual.append(pending_output_data)
        if len(actual) == 16:
            dut.i_valid.value = 0
            return bytes(actual)

        # These are the DUT values for the current cycle.  The handshake we
        # arrange below is sampled at the next rising edge.
        o_ready = cycle % OUTPUT_STROBE_CYCLES == 0
        dut.o_ready.value = o_ready

        o_valid = as_int(dut.o_valid.value)
        o_data = as_int(dut.o_data.value)
        pending_output_data = o_data if o_valid and o_ready else None

        # i_valid is a one-clock software strobe, not a sustained streaming
        # valid.  A byte not accepted at its slot is retried five cycles later.
        input_valid = (
            cycle % INPUT_STROBE_CYCLES == 0
            and input_index < len(input_stream)
        )
        dut.i_valid.value = input_valid
        dut.i_data.value = input_stream[input_index] if input_valid else 0
        pending_input_taken = input_valid and as_int(dut.i_ready.value)

        await RisingEdge(dut.clk)

    raise AssertionError(
        "AES transaction did not finish after 10,000 cycles "
        f"(sent {input_index}/{len(input_stream)} input bytes, "
        f"received {len(actual)}/16 output bytes)"
    )


async def check_aes(dut, r_dec, key_length):
    decrypt = bool(r_dec & 0b10)
    if decrypt:
        input_bytes = EXPECTED[key_length]
        key_bytes = (
            DECRYPTION_KEY_STATE[key_length]
            if r_dec == 0b10
            else bytes(range(key_length))
        )
        expected = DATA
    else:
        input_bytes = DATA
        key_bytes = bytes(range(key_length))
        expected = EXPECTED[key_length]
    actual = await run_aes(dut, r_dec, input_bytes, key_bytes)
    direction = "decrypt" if decrypt else "encrypt"
    assert actual == expected, (
        f"AES-{key_length * 8} {direction} returned {actual.hex()}, "
        f"expected {expected.hex()}"
    )


@cocotb.test()
async def test_aes128_encrypt(dut):
    cocotb.start_soon(Clock(dut.clk, 10, unit="ns").start())
    await check_aes(dut, r_dec=0b00, key_length=16)


