"""End-to-end AES tests for the byte-streaming AesTop interface.

Each transaction sends the 16-byte input block first, followed by its key.
Encryption tests exercise the implemented byte-streaming path.  Decryption
tests are ready for the same round-trip vectors but remain skipped until
ControlFsm has decryption microcode.
"""

import cocotb
from cocotb.clock import Clock
from cocotb.triggers import RisingEdge


DATA = bytes.fromhex("00112233445566778899aabbccddeeff")
KEY_LEVEL = {16: 0b00, 24: 0b01, 32: 0b10}

# AES ECB results for DATA=00112233445566778899aabbccddeeff and the
# incrementing key of the corresponding length.  These are the three FIPS-197
# encryption known-answer values.  A decrypt transaction consumes the matching
# ciphertext below and must recover DATA.
EXPECTED = {
    16: bytes.fromhex("69c4e0d86a7b0430d8cdb78070b4c55a"),
    24: bytes.fromhex("dda97ca4864cdfe06eaf70a0ec0d7191"),
    32: bytes.fromhex("8ea2b7ca516745bfeafc49904b496089"),
}

# Decryption starts from the end of the key schedule.  AesTop's key register
# is key-width wide, therefore AES-192/AES-256 need the final 24/32-byte key
# schedule state (not merely the final 16-byte AddRoundKey value).  These
# values are generated by model.aes.decryption_key_state(bytes(range(n))).
DECRYPTION_KEY_STATE = {
    16: bytes.fromhex("13111d7fe3944a17f307a78b4d2b30c5"),
    24: bytes.fromhex("a223800fd8aeda32a4970a331a78dc09c418c271e3a41d5d"),
    32: bytes.fromhex("4e5a6699a9f24fe07e572baacdf8cdea24fc79ccbf0979e9371ac23c6d68de36"),
}


def as_int(value):
    return int(value)


async def reset(dut):
    dut.rst_n.value = 0
    dut.i_valid.value = 0
    dut.i_data.value = 0
    dut.o_ready.value = 1
    await RisingEdge(dut.clk)
    await RisingEdge(dut.clk)
    dut.rst_n.value = 1
    await RisingEdge(dut.clk)


async def send_byte(dut, value):
    dut.i_data.value = value
    dut.i_valid.value = 1
    while not as_int(dut.i_ready.value):
        await RisingEdge(dut.clk)
    await RisingEdge(dut.clk)


async def run_aes(dut, decrypt, input_bytes, key_bytes):
    dut.r_dec.value = int(decrypt)
    dut.r_level.value = KEY_LEVEL[len(key_bytes)]
    await reset(dut)

    for value in input_bytes + key_bytes:
        await send_byte(dut, value)
    dut.i_valid.value = 0

    actual = bytearray()
    for _ in range(16):
        for _ in range(1_000):
            if as_int(dut.o_valid.value):
                break
            await RisingEdge(dut.clk)
        else:
            raise AssertionError("AES output did not become valid")
        actual.append(as_int(dut.o_data.value))
        await RisingEdge(dut.clk)
    return bytes(actual)


async def check_aes(dut, decrypt, key_length):
    if decrypt:
        input_bytes = EXPECTED[key_length]
        key_bytes = DECRYPTION_KEY_STATE[key_length]
        expected = DATA
    else:
        input_bytes = DATA
        key_bytes = bytes(range(key_length))
        expected = EXPECTED[key_length]
    actual = await run_aes(dut, decrypt, input_bytes, key_bytes)
    direction = "decrypt" if decrypt else "encrypt"
    assert actual == expected, (
        f"AES-{key_length * 8} {direction} returned {actual.hex()}, "
        f"expected {expected.hex()}"
    )


@cocotb.test()
async def test_aes128_encrypt(dut):
    cocotb.start_soon(Clock(dut.clk, 10, unit="ns").start())
    await check_aes(dut, decrypt=False, key_length=16)


@cocotb.test()
async def test_aes192_encrypt(dut):
    cocotb.start_soon(Clock(dut.clk, 10, unit="ns").start())
    await check_aes(dut, decrypt=False, key_length=24)


@cocotb.test()
async def test_aes256_encrypt(dut):
    cocotb.start_soon(Clock(dut.clk, 10, unit="ns").start())
    await check_aes(dut, decrypt=False, key_length=32)


@cocotb.test()
async def test_aes128_decrypt(dut):
    cocotb.start_soon(Clock(dut.clk, 10, unit="ns").start())
    await check_aes(dut, decrypt=True, key_length=16)


